class Command(BaseCommand):
    help = "初始化网络梗知识库（约35条常见中文梗）"

    def add_arguments(self, parser):
        parser.add_argument(
            "--reset",
            action="store_true",
            help="先清空所有 Meme 记录再重建",
        )

    def handle(self, *args, **options):
        if options["reset"]:
            deleted, _ = Meme.objects.all().delete()
            self.stdout.write(self.style.WARNING(f"已清空 {deleted} 条梗记录"))

        created_count = 0
        skipped_count = 0

        for name, keywords, explanation, origin, category in MEMES_DATA:
            obj, created = Meme.objects.update_or_create(
                name=name,
                defaults={
                    "keywords": keywords,
                    "explanation": explanation,
                    "origin": origin,
                    "category": category,
                    "is_active": True,
                },
            )
            if created:
                created_count += 1
            else:
                skipped_count += 1

        self.stdout.write(self.style.SUCCESS(
            f"✅ 梗知识库初始化完成！\n"
            f"   新增: {created_count} 条\n"
            f"   更新/已存在: {skipped_count} 条\n"
            f"   总计: {Meme.objects.count()} 条"
        ))
